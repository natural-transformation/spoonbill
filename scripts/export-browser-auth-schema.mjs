import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

// Runtime initialization and the complete migration chain must describe the
// same schema. Applied versioned migrations remain byte-for-byte immutable.
// This is deliberately not a general SQL or Scala parser.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const directory = path.join(root, 'modules/security-jdbc/src/main/scala/spoonbill/security/jdbc');
function statements(file, vector) {
  const source = readFileSync(path.join(directory, file), 'utf8');
  const start = vector ? /private\s+val\s+schema\s*=\s*Vector\(/.exec(source) : null;
  assert(!vector || start, `Missing literal schema vector in ${file}`);
  const section = start ? source.slice(start.index + start[0].length) : source;
  const ddl = [...section.matchAll(/"""([\s\S]*?)"""/g)].map(match => match[1].trim())
    .filter(text => /^(CREATE|ALTER)\s/.test(text));
  assert(ddl.length > 0, `No deployment DDL in ${file}`);
  return ddl;
}
const retention = statements('JdbcBrowserRetention.scala', true);
const sql = [
  ...statements('JdbcBrowserClock.scala', false),
  ...statements('JdbcBrowserSessions.scala', true),
  ...statements('JdbcBrowserPersistence.scala', true),
  ...retention,
];
assert.equal(sql.filter(value => value.startsWith('CREATE TABLE')).length, 11,
  'Review the deployment migration when framework table coverage changes');
const destination = path.join(root, 'modules/security-jdbc/src/main/resources/spoonbill/migrations/postgresql/V4__browser_auth.sql');
// Historical V4 from 7108eda8cef0d6d8ab838fe8c963f58cda810887. Neither mode
// writes this file: new schema changes belong in forward migrations.
const baseline = readFileSync(destination);
assert.equal(createHash('sha256').update(baseline).digest('hex'),
  '0878c9f08779d55b2a610160f757e69a3189c39b79d67f74000affc52d82a322',
  'Historical V4 migration changed; restore its original bytes, never regenerate it');
const baselineSql = baseline.toString('utf8').split(/\r?\n/).filter(line => !line.trim().startsWith('--'))
  .join('\n').split(';').map(value => value.trim()).filter(Boolean);
assert.equal(baselineSql.filter(value => value.startsWith('CREATE TABLE')).length, 8,
  'Historical V4 must retain its eight framework tables');
const upgrade = sql.filter(value => /^(CREATE TABLE IF NOT EXISTS spoonbill_browser_replacement\s|CREATE UNIQUE INDEX IF NOT EXISTS spoonbill_browser_replacement_reservation\s|CREATE INDEX IF NOT EXISTS spoonbill_browser_replacement_successor\s)/.test(value));
assert.equal(upgrade.length, 3, 'Replacement upgrade must create linkage, reservation uniqueness and successor lookup');
const upgradeDestination = path.join(root, 'modules/security-jdbc/src/main/resources/spoonbill/migrations/postgresql/V5__authenticated_session_replacement.sql');
const historicalUpgrade = readFileSync(upgradeDestination);
assert.equal(createHash('sha256').update(historicalUpgrade).digest('hex'),
  '254680c4ba844d9c63e617fbe89aab36bc2f4e3a245f7c0e9bf9051256b4d8fe',
  'Historical V5 migration changed; restore its original bytes, never regenerate it');
const upgradeSql = historicalUpgrade.toString('utf8').split(/\r?\n/).filter(line => !line.trim().startsWith('--'))
  .join('\n').split(';').map(value => value.trim()).filter(Boolean);
const normalized = values => values.map(value => value.replace(/\s+/g, ' ').trim()).sort();
assert.deepEqual(normalized(upgradeSql), normalized(upgrade),
  'Frozen V5 must retain the exact replacement runtime DDL; use a forward migration for changes');
assert.equal(retention.length, 4, 'Retention upgrade must define permanent scope metadata, shared work cadence and both last_seen columns');
assert.deepEqual(normalized([...baselineSql, ...upgradeSql, ...retention]), normalized(sql),
  'Frozen V4 and V5 plus the forward retention upgrade must cover runtime DDL exactly; review a new migration for other changes');
const retentionResult = '-- Spoonbill bounded browser retention: explicit PostgreSQL forward upgrade.\n' +
  '-- Generated by scripts/export-browser-auth-schema.mjs; do not edit directly.\n' +
  '-- Drain every old serving/writing binary first; do not run mixed versions.\n' +
  '-- Apply after V4 and V5 in one transaction before retention-aware nodes start.\n' +
  '-- Existing slot/view activity starts at migration time, delaying initial reclamation.\n' +
  '-- The provider creates per-scope issuance/floor metadata while holding its realm admission lock.\n' +
  '-- Reclamation is incompatible with rollback to binaries that ignore these permanent fences.\n' +
  '-- Rollbacks must remain retention-aware and preserve metadata and host transaction guarantees.\n' +
  '-- NEVER delete a reclamation-floor record, reset its counters/floors, or drop this metadata table.\n\n' +
  retention.map(value => value + ';').join('\n\n') + '\n';
const retentionDestination = path.join(root, 'modules/security-jdbc/src/main/resources/spoonbill/migrations/postgresql/V6__browser_retention.sql');
const [mode = '--check'] = process.argv.slice(2);
assert(['--check', '--write'].includes(mode), 'Use --check or --write');
if (mode === '--write') {
  mkdirSync(path.dirname(retentionDestination), {recursive: true});
  writeFileSync(retentionDestination, retentionResult);
} else {
  assert.equal(readFileSync(retentionDestination, 'utf8'), retentionResult, 'Retention upgrade DDL is stale');
}
console.log(JSON.stringify({status: 'pass', mode, statements: sql.length, tables: 11,
  baselineStatements: baselineSql.length, baselineTables: 8, upgradeStatements: upgrade.length, upgradeTables: 1,
  retentionStatements: retention.length, retentionTables: 2}));
